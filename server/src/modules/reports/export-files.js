import zlib from 'node:zlib';

/*
 * CSV and XLSX writers with no third-party code. Each column is { key, label, type } where type
 * is 'text' | 'number' | 'date'. Dates are 'YYYY-MM-DD' strings and stay text in CSV.
 */

/** Text that a spreadsheet would treat as a formula is prefixed with ' (OWASP CSV injection). */
export function neutralise(value) {
  if (typeof value !== 'string') return value;
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
}

export function toCsv(columns, rows) {
  const cell = (v) => {
    if (v === null || v === undefined) return '';
    const s = String(neutralise(typeof v === 'number' ? v : String(v)));
    return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = [columns.map((c) => cell(c.label)).join(',')];
  for (const r of rows) lines.push(columns.map((c) => cell(r[c.key])).join(','));
  // BOM so Excel opens UTF-8 names correctly.
  return Buffer.from(`\uFEFF${lines.join('\r\n')}\r\n`, 'utf8');
}

