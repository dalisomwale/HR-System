// XLSX: a minimal Office Open XML workbook, zipped with zlib.

const xml = (s) =>
  String(s)
    // Characters XML 1.0 does not allow.
    // eslint-disable-next-line no-control-regex
    .replace(/[\x00-\x08\x0B\x0C\x0E-\x1F]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function colName(i) {
  let n = i + 1;
  let s = '';
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

/** Excel serial day number for a 'YYYY-MM-DD' date. */
function serial(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000;
}

function sheetXml(columns, rows) {
  const widths = columns.map((c) =>
    Math.min(
      60,
      Math.max(
        c.label.length,
        ...rows.slice(0, 500).map((r) => String(r[c.key] ?? '').length),
        c.type === 'date' ? 11 : 6,
      ) + 2,
    ),
  );
  const head = columns
    .map((c, i) => `<c r="${colName(i)}1" t="inlineStr" s="1"><is><t>${xml(c.label)}</t></is></c>`)
    .join('');
  const body = rows
    .map((r, ri) => {
      const rn = ri + 2;
      const cells = columns
        .map((c, ci) => {
          const v = r[c.key];
          const ref = `${colName(ci)}${rn}`;
          if (v === null || v === undefined || v === '') return '';
          if (c.type === 'number' && Number.isFinite(Number(v)))
            return `<c r="${ref}"><v>${Number(v)}</v></c>`;
          if (c.type === 'date' && /^\d{4}-\d{2}-\d{2}$/.test(String(v)))
            return `<c r="${ref}" s="2"><v>${serial(String(v))}</v></c>`;
          // Inline strings are never evaluated as formulas, so no prefix is needed here.
          return `<c r="${ref}" t="inlineStr"><is><t xml:space="preserve">${xml(v)}</t></is></c>`;
        })
        .join('');
      return `<row r="${rn}">${cells}</row>`;
    })
    .join('');
  const last = `${colName(columns.length - 1)}${rows.length + 1}`;
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><dimension ref="A1:${last}"/><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><cols>${widths
    .map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`)
    .join(
      '',
    )}</cols><sheetData><row r="1">${head}</row>${body}</sheetData><autoFilter ref="A1:${last}"/></worksheet>`;
}

